def path(coords,fill,stroke=None,sw=1):
 points=[]
 for cmd,pts in coords:
  if cmd=='M' or cmd=='L':points.append(pts)
  elif cmd=='C':
   x0,y0=points[-1];x1,y1,x2,y2,x3,y3=pts
   for n in range(1,33):
    t=n/32;u=1-t
    points.append((u*u*u*x0+3*u*u*t*x1+3*u*t*t*x2+t*t*t*x3,u*u*u*y0+3*u*u*t*y1+3*u*t*t*y2+t*t*t*y3))
  elif cmd=='Z':points.append(points[0])
 if fill:poly(points,fill)
 if stroke:line(points,stroke,sw)
